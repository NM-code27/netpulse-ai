"use client";

import { useState } from "react";
import useSWR from "swr";
import { api } from "@/lib/api";
import { TopBar } from "@/components/TopBar";
import { AlertCard } from "@/components/AlertCard";

export default function AlertsPage() {
  const [filter, setFilter] = useState<"unresolved" | "all">("unresolved");
  const { data: alerts, mutate } = useSWR(
    ["alerts", filter], () => api.alerts(filter === "unresolved" ? false : undefined, 100),
    { refreshInterval: 5000 }
  );

  return (
    <>
      <TopBar title="Alerts" subtitle="Anomalies and predictive-risk warnings generated by the scoring engine" />
      <div className="p-6">
        <div className="mb-4 flex gap-2">
          {(["unresolved", "all"] as const).map((f) => (
            <button
              key={f}
              onClick={() => setFilter(f)}
              className="rounded-full px-3.5 py-1.5 text-xs font-semibold transition-colors"
              style={{
                background: filter === f ? "var(--accent-gradient)" : "var(--surface)",
                color: filter === f ? "white" : "var(--text-muted)",
                border: "1px solid var(--border)",
                boxShadow: filter === f ? "0 4px 12px -4px rgba(42,110,224,0.5)" : "none",
              }}
            >
              {f === "unresolved" ? "Unresolved" : "All"}
            </button>
          ))}
        </div>

        <div className="space-y-2">
          {alerts && alerts.length > 0 ? (
            alerts.map((a) => <AlertCard key={a.id} alert={a} onResolved={() => mutate()} />)
          ) : (
            <p className="text-sm" style={{ color: "var(--text-muted)" }}>
              No alerts to show.
            </p>
          )}
        </div>
      </div>
    </>
  );
}
